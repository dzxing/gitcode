import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { createServer } from 'vite'
const vite = await createServer({
  configFile: false,
  optimizeDeps: { noDiscovery: true, entries: [] },
  server: { middlewareMode: true, hmr: false, ws: false, watch: null },
  appType: 'custom',
})
const branch = (name, hash, kind = 'local') => ({
  name,
  hash,
  kind,
  current: false,
  upstream: '',
  track: '',
})
try {
  const { ideaGraphLayout } = await vite.ssrLoadModule('/src/ideaGraphLayout.ts')
  const { buildGraph } = await vite.ssrLoadModule('/src/graph.ts')
  await test('native IDEA print elements agree on row columns, half-edge extents and arrow-aware width', async () => {
    const { cases } = JSON.parse(
      await fs.readFile(new URL('./fixtures/idea-print-layout.json', import.meta.url)),
    )
    for (const fixture of cases) {
      const commits = fixture.parents.map((parents, row) => ({
        hash: `c${row}`,
        parents: parents.map((p) => `c${p}`),
      }))
      const refs = fixture.refs.map((row) =>
        branch(`feature/${String(row).padStart(4, '0')}`, `c${row}`),
      )
      const actual = ideaGraphLayout(commits, refs, true, new Set(), !fixture.show)
      assert.deepEqual(actual.lanes, fixture.lanes)
      assert.deepEqual(actual.rowMaxIndices, fixture.rowMaxIndices)
      assert.equal(actual.recommendedWidth, fixture.recommendedWidth)
    }
  })
  await test('adding a tag to a non-head never creates a traversal head or changes fragment identity', () => {
    const commits = [
      { hash: 'a', parents: ['root'] },
      { hash: 'b', parents: ['root'] },
      { hash: 'root', parents: [] },
    ]
    const plain = ideaGraphLayout(commits)
    const tagged = ideaGraphLayout(commits, [branch('v1', 'root', 'tag')])
    assert.deepEqual([...plain.fragments], [1, 2, 1])
    assert.deepEqual([...tagged.fragments], [...plain.fragments])
    assert.deepEqual([...tagged.owners], [...plain.owners])
    assert.deepEqual(
      buildGraph(commits).nodes,
      buildGraph(commits, 1, undefined, false, [branch('v1', 'root', 'tag')]).nodes,
    )
  })
  // Generated by executing unmodified IDEA 262.10968.63 classes, not this port.
  const golden = JSON.parse(
    await fs.readFile(new URL('./fixtures/idea-layout.json', import.meta.url)),
  )
  await test('fragment ordering and row compaction match native IDEA classes on 20 reference DAGs', () => {
    for (const fixture of golden) {
      const commits = fixture.parents.map((parents, index) => ({
        hash: `c${index}`,
        parents: parents.map((p) => `c${p}`),
      }))
      const branches = fixture.refs.map((i) =>
        branch(`feature/${String(i).padStart(4, '0')}`, `c${i}`),
      )
      const actual = ideaGraphLayout(commits, branches)
      assert.deepEqual([...actual.fragments], fixture.fragments)
      assert.deepEqual(actual.lanes, fixture.lanes)
    }
  })
  await test('origin main/master, remote, local main/master and local refs set fragment precedence', () => {
    const commits = [
      { hash: 'topic', parents: ['base'] },
      { hash: 'main', parents: ['base'] },
      { hash: 'base', parents: [] },
    ]
    for (const production of ['main', 'master']) {
      const refs = [
        branch('topic', 'topic'),
        branch(production, 'main'),
        branch(`origin/${production}`, 'main', 'remote'),
      ]
      const graph = buildGraph(commits, 0, undefined, false, refs)
      const order = ideaGraphLayout(commits, refs)
      assert.ok(order.fragments[1] < order.fragments[0])
      assert.equal(graph.nodes[1].x, 24)
      assert.equal(graph.nodes[1].color, graph.nodes[2].color)
      const reversed = buildGraph(
        commits,
        0,
        undefined,
        false,
        [...refs].reverse().map((b) => ({ ...b, current: !b.current })),
      )
      assert.deepEqual(graph, reversed)
      assert.deepEqual(
        commits.map((c) => c.hash),
        ['topic', 'main', 'base'],
      )
    }
  })
  await test('references on a non-tip commit participate and reference names sort numerically', () => {
    const commits = [
      { hash: 'tip', parents: ['base'] },
      { hash: 'other', parents: ['base'] },
      { hash: 'base', parents: [] },
    ]
    const graph = ideaGraphLayout(commits, [
      branch('main', 'base'),
      branch('feature/10', 'tip'),
      branch('feature/2', 'other'),
    ])
    assert.equal(graph.fragments[2], 1)
    assert.ok(graph.fragments[1] < graph.fragments[0])
  })
  await test('symbols and current checkout do not become competing branch priorities', () => {
    const commits = [
      { hash: 'left', parents: ['base'] },
      { hash: 'right', parents: ['base'] },
      { hash: 'base', parents: [] },
    ]
    const refs = [branch('feature/2', 'left'), branch('feature/10', 'right')]
    const baseline = buildGraph(commits, 0, undefined, false, refs)
    const changed = buildGraph(commits, 0, undefined, false, [
      ...refs.map((b) => ({ ...b, current: !b.current })),
      { ...branch('origin/HEAD', 'right', 'remote'), symbolicTarget: 'origin/main' },
    ])
    assert.deepEqual(baseline, changed)
  })
  await test('a real branch named HEAD remains a reference unless it is explicitly symbolic', () => {
    const commits = [
      { hash: 'first', parents: ['base'] },
      { hash: 'named', parents: ['base'] },
      { hash: 'base', parents: [] },
    ]
    const layout = ideaGraphLayout(commits, [branch('feature/HEAD', 'named')])
    assert.ok(layout.fragments[1] < layout.fragments[0])
  })
  await test('duplicate parents collapse and incomplete history has bounded boundary stubs', () => {
    const graph = buildGraph(
      [
        { hash: 'tip', parents: ['base', 'base', 'absent'] },
        { hash: 'base', parents: [] },
      ],
      0,
    )
    assert.equal(graph.edges.length, 2)
    assert.equal(graph.nodes[0].merge, true)
    assert.equal(graph.edges.filter((e) => e.boundary).length, 1)
    assert.ok(graph.edges.every((e) => !e.d.includes('NaN')))
  })
  await test('a long ancestry track does not generate thousands of redundant SVG commands', () => {
    const commits = [
      { hash: 'long', parents: ['root'] },
      ...Array.from({ length: 3000 }, (_, i) => ({
        hash: `side${i}`,
        parents: [i < 2999 ? `side${i + 1}` : 'root'],
      })),
      { hash: 'root', parents: [] },
    ]
    const graph = buildGraph(commits, 0)
    const edge = graph.edges.find((edge) => edge.childHash === 'long')
    assert.ok(edge.d.length < 200)
    assert.equal(edge.parentHash, 'root')
    assert.equal(edge.boundary, false)
  })
  const longMerge = (span) => [
    { hash: 'merge', parents: ['side0', 'base'] },
    ...Array.from({ length: span - 1 }, (_, i) => ({
      hash: `side${i}`,
      parents: [i < span - 2 ? `side${i + 1}` : 'base'],
    })),
    { hash: 'base', parents: [] },
  ]
  await test('IDEA long-edge threshold is 30 rows and arrows target actual edge endpoints', () => {
    assert.equal(buildGraph(longMerge(29), 0).arrows.length, 0)
    const graph = buildGraph(longMerge(30), 0)
    assert.deepEqual(
      graph.arrows.map((a) => [a.direction, a.targetHash]),
      [
        ['down', 'base'],
        ['up', 'merge'],
      ],
    )
    assert.equal(graph.arrows[0].fromY, 45)
    assert.equal(graph.arrows[0].y, 56.75)
    assert.equal(graph.arrows[1].fromY, 30 * 29 + 15)
    assert.equal(graph.arrows[1].y, 873.25)
    assert.equal(
      graph.edges.find((e) => e.childHash === 'merge' && e.parentHash === 'base').d.match(/M/g)
        .length,
      2,
    )
    for (const arrow of graph.arrows) {
      const node = graph.nodes.find((node) => node.y === arrow.fromY)
      assert.ok(!node || Math.abs(node.x - arrow.x) >= 22)
    }
  })
  await test('show long edges keeps navigation and only truncates at 1000 rows with 250-row attachments', () => {
    const full = buildGraph(longMerge(60), 0, undefined, false, [], new Set(), false)
    const edge = full.edges.find((edge) => edge.childHash === 'merge' && edge.parentHash === 'base')
    assert.equal(edge.d.match(/M/g).length, 1)
    assert.equal(full.arrows.length, 2)
    assert.equal(full.arrows[0].terminal, false)
    assert.equal(full.arrows[0].y, 60)
    const huge = buildGraph(longMerge(1000), 0, undefined, false, [], new Set(), false)
    assert.equal(huge.arrows[0].terminal, true)
    assert.equal(huge.arrows[0].fromY, 250 * 30 + 15)
    assert.equal(huge.arrows[1].fromY, 750 * 30 + 15)
    assert.equal(
      huge.edges
        .find((edge) => edge.childHash === 'merge' && edge.parentHash === 'base')
        .d.match(/M/g).length,
      2,
    )
  })
  await test('arrow hit ellipse reproduces IDEA sum-of-distances edge detection', async () => {
    const { graphArrowHit } = await vite.ssrLoadModule('/src/graphPainting.ts')
    const arrow = { fromX: 0, fromY: 0, otherX: 22, otherY: 30 }
    const hit = graphArrowHit(arrow, 2),
      angle = (hit.angle * Math.PI) / 180
    for (const x of [-5, 0, 8, 11, 22, 27])
      for (const y of [-5, 0, 10, 15, 30, 35]) {
        const distance = Math.hypot(x, y) + Math.hypot(x - 22, y - 30)
        const cutoff = Math.hypot(22, 30) + 2
        if (Math.abs(distance - cutoff) < 0.00001) continue
        const dx = x - hit.cx,
          dy = y - hit.cy
        const value =
          ((dx * Math.cos(angle) + dy * Math.sin(angle)) / hit.rx) ** 2 +
          ((-dx * Math.sin(angle) + dy * Math.cos(angle)) / hit.ry) ** 2
        assert.equal(value < 1, distance < cutoff)
      }
  })
  await test('unloaded parents expose a down target without inventing an up destination', () => {
    const commits = longMerge(40).slice(0, 35)
    const graph = buildGraph(commits, 0, undefined, true)
    const down = graph.arrows.find(
      (arrow) => arrow.childHash === 'merge' && arrow.parentHash === 'base',
    )
    assert.equal(down.targetHash, 'base')
    assert.equal(down.direction, 'down')
    assert.ok(
      !graph.arrows.some((arrow) => arrow.parentHash === 'base' && arrow.direction === 'up'),
    )
  })
  await test('paint coordinates and reference endpoints share device pixels at common Windows scales', async () => {
    const { graphPaint, paintHistoryGraph } = await vite.ssrLoadModule('/src/graphPainting.ts')
    const { buildHistoryGraph } = await vite.ssrLoadModule('/src/graph.ts')
    const commits = longMerge(40).map((commit) => ({
      ...commit,
      date: '2026-11-09T00:00:00Z',
      refs: [],
      author: '',
      email: '',
      subject: commit.hash,
    }))
    for (const ratio of [1, 1.25, 1.5, 2]) {
      const viewport = { ratio, scaleX: 1, scaleY: 1, phaseX: 0.25, phaseY: 0.75 }
      const paint = graphPaint(viewport)
      const graph = paintHistoryGraph(buildHistoryGraph(commits, [], false), viewport)
      const parity = (Math.round(paint.lineWidth * ratio) % 2) / 2
      for (const node of graph.nodes) {
        for (const physical of [node.x * ratio + viewport.phaseX, node.y * ratio + viewport.phaseY])
          assert.ok(Math.abs(physical - parity - Math.round(physical - parity)) < 0.0002)
      }
      for (const edge of graph.edges.filter((edge) => !edge.boundary)) {
        const endpoint = [...edge.d.matchAll(/([MLV])([^MLV]*)/g)].at(-1)
        const values = endpoint[2].trim().split(/[ ,]+/).map(Number)
        const parent = graph.nodes.find((node) => node.hash === edge.parentHash)
        assert.equal(values.at(-1), parent.y)
        if (endpoint[1] !== 'V') assert.equal(values[0], parent.x)
      }
    }
  })
  await test('navigation arrowheads follow diagonal edge direction in both directions', async () => {
    const { graphArrowPath } = await vite.ssrLoadModule('/src/graphPainting.ts')
    for (const [x, y] of [
      [22, 30],
      [-22, -30],
      [0, 30],
    ]) {
      const d = graphArrowPath({ x, y, fromX: 0, fromY: 0 })
      const points = [...d.matchAll(/[ML]([^ML]+)/g)].map((match) =>
        match[1].trim().split(/[ ,]+/).map(Number),
      )
      const dx = x - (points[0][0] + points[2][0]) / 2
      const dy = y - (points[0][1] + points[2][1]) / 2
      assert.ok(Math.abs(dx * y - dy * x) < 0.01)
      assert.ok(dx * x + dy * y > 0)
    }
  })
  await test('deep history uses an iterative traversal and preserves all ancestry endpoints', () => {
    const count = 20000
    const commits = Array.from({ length: count }, (_, i) => ({
      hash: `c${i}`,
      parents: i + 1 < count ? [`c${i + 1}`] : [],
    }))
    const graph = buildGraph(commits, 0, undefined, false, [branch('main', 'c0')])
    assert.equal(graph.nodes.length, count)
    assert.equal(graph.edges.length, count - 1)
    assert.ok(graph.nodes.every((n) => n.x === 24))
    assert.equal(graph.width, 68)
  })
  await test('row text width reclaims narrow history and includes diagonal half-row extents', () => {
    const commits = Array.from({ length: 100 }, (_, row) => ({
      hash: `c${row}`,
      parents: row < 12 ? ['c12'] : row < 99 ? [`c${row + 1}`] : [],
    }))
    const layout = ideaGraphLayout(commits)
    const graph = buildGraph(commits)
    assert.ok(graph.rowWidths.get('c11') > graph.rowWidths.get('c99'))
    assert.ok(graph.recommendedWidth <= 148, 'recommended baseline is capped at six lanes')
    assert.ok(graph.rowWidths.get('c11') > graph.recommendedWidth)
    const dense = commits.map((commit, row) => ({
      ...commit,
      parents: row < 12 ? ['c87'] : commit.parents,
    }))
    assert.ok(ideaGraphLayout(dense).recommendedWidth > 6)
    assert.equal(buildGraph(dense, 0, undefined, false, [], new Set(), false).recommendedWidth, 148)
    for (const edge of layout.edges) {
      const route = [
        { row: edge.child, position: layout.lanes[edge.child] },
        ...edge.positions,
        { row: edge.parent, position: layout.lanes[edge.parent] },
      ]
      for (let i = 1; i < route.length; i++) {
        const a = route[i - 1],
          b = route[i]
        const midpointX = 24 + ((a.position + b.position) / 2) * 22
        for (const row of [a.row, b.row])
          assert.ok(graph.rowWidths.get(`c${row}`) >= midpointX + 14)
      }
    }
  })
  await test('compact arrow ornaments retain thick main lines across desktop scales', async () => {
    const { graphPaint, graphArrowPath } = await vite.ssrLoadModule('/src/graphPainting.ts')
    for (const ratio of [1, 1.25, 1.5, 2]) {
      const paint = graphPaint({ ratio, scaleX: 1, scaleY: 1, phaseX: 0, phaseY: 0 })
      assert.ok(paint.arrowWidth < paint.lineWidth)
      assert.ok(paint.radius >= 4)
    }
    const path = graphArrowPath({ x: 0, y: 15, fromX: 0, fromY: 0 })
    const wing = path.match(/^M([^ ]+) ([^ ]+)/)
    assert.ok(Math.abs(Math.hypot(Number(wing[1]), Number(wing[2]) - 15) - 6.6) < 0.001)
  })
} finally {
  await vite.close()
}
