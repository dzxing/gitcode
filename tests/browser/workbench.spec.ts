import { expect, test } from '@playwright/test'
import { openFixtureRepository, openRepositoryFallback } from './repository-fixture'

test('repository history, searching, file diff, modal and shortcuts', async ({ page }) => {
  await openFixtureRepository(page)
  await expect(page.getByText('演示模式', { exact: true })).toHaveCount(0)
  await expect(page.locator('.commit-row')).toHaveCount(16)
  await page.getByRole('textbox', { name: '搜索提交', exact: true }).fill('Lin Wang')
  await expect(page.locator('.commit-row')).toHaveCount(4)
  await page.getByRole('button', { name: '清除搜索' }).click()
  const historyNav = page.getByRole('navigation', { name: '工作区导航' })
  await historyNav.getByRole('button', { name: /提交历史/ }).click()
  await expect(historyNav.getByRole('button', { name: /提交历史/ })).toHaveClass(/active/)
  const firstRow = page.locator('.commit-row').first()
  await expect(firstRow).toHaveCSS('height', '30px')
  await firstRow.locator('button.ref-inspect').click()
  const refs = page.getByRole('dialog', { name: '提交引用' })
  await expect(refs).toBeVisible()
  await expect(refs.getByText('origin/main', { exact: true })).toBeVisible()
  await refs.getByRole('button', { name: '关闭引用列表' }).click()
  await expect(firstRow.locator('button.ref-inspect')).toBeFocused()
  await firstRow.locator('.commit-select').click()
  await expect(page.getByText('提交详情', { exact: true })).toBeVisible()
  await page.locator('.file-main').first().click()
  await expect(page.getByRole('region', { name: '文件差异' })).toBeVisible()
  await expect(page.locator('.diff-line.add')).not.toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('region', { name: '文件差异' })).not.toBeVisible()
  await openRepositoryFallback(page)
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('仓库路径', { exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
})

test('new tab opens the repository hub and returns to the existing workspace', async ({ page }) => {
  await openFixtureRepository(page)
  await page.getByRole('textbox', { name: '提交说明', exact: true }).fill('保留我的草稿')
  await page.getByRole('button', { name: '新建标签页', exact: true }).click()
  const hub = page.getByRole('main', { name: '新标签页', exact: true })
  await expect(hub).toBeVisible()
  await expect(page.locator('.toolbar')).toHaveCount(0)
  await hub.getByRole('button', { name: '克隆仓库', exact: true }).click()
  await expect(page.getByLabel('仓库地址', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '关闭标签 新标签页', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '提交说明', exact: true })).toHaveValue(
    '保留我的草稿',
  )
  await expect(page.locator('.workbench')).toBeVisible()
})

test('fresh startup and closing the last repository show a clean hub without sample data', async ({
  page,
}) => {
  await page.goto('/')
  const hub = page.getByRole('main', { name: '新标签页', exact: true })
  await expect(hub).toBeVisible()
  await expect(page.locator('.workbench,.commit-row,.wip-row,.toolbar')).toHaveCount(0)
  await expect(page.getByText('演示模式', { exact: true })).toHaveCount(0)
  await hub.getByRole('button', { name: '打开仓库', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '打开本地仓库', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await hub.getByRole('button', { name: '克隆仓库', exact: true }).click()
  await expect(page.getByLabel('仓库地址', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await openFixtureRepository(page)
  await page.getByRole('button', { name: '关闭标签 GitCode', exact: true }).click()
  await expect(hub).toBeVisible()
  await expect(page.locator('.workbench,.commit-row,.wip-row,.toolbar')).toHaveCount(0)
})
